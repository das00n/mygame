const sorted = TERMS.flatMap((t) => (t.match ?? [t.term]).map((m) => ({ m, t }))).sort((a, b) => b.m.length - a.m.length);

export interface TextPart {
  text: string;
  term?: Term;
}

/** 문장을 낱말 단위로 쪼갠다 (긴 낱말 먼저) */
export function splitTerms(text: string): TextPart[] {
  const out: TextPart[] = [];
  let i = 0;
  let buf = '';
  outer: while (i < text.length) {
    for (const { m, t } of sorted) {
      if (text.startsWith(m, i)) {
        if (buf) out.push({ text: buf });
        buf = '';
        out.push({ text: m, term: t });
        i += m.length;
        continue outer;
      }
    }
    buf += text[i];
    i++;
  }
  if (buf) out.push({ text: buf });
  return out;
}

export function termsIn(text: string): Term[] {
  const seen = new Set<Term>();
  for (const p of splitTerms(text)) if (p.term) seen.add(p.term);
  return [...seen];
}
